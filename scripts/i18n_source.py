HEADER = """// Сгенерировано scripts/i18n_source.py — правьте исходник и запускайте его, а не этот файл.
// Ключ — русский текст интерфейса (I18N_TASKS.md, раздел 2).
window.CHECKAI_LOCALES = window.CHECKAI_LOCALES || {};
"""


def build() -> None:
    seen = {}
    for ru, kk, en in T:
        if ru in seen and seen[ru] != (kk, en):
            raise SystemExit(f"Ключ с разными переводами: {ru!r}: {seen[ru]} / {(kk, en)}")
        seen[ru] = (kk, en)
    out_dir = os.path.join(os.path.dirname(__file__), "..", "frontend", "static", "js", "locales")
    for idx, lang in enumerate(("kk", "en")):
        lines = [f"  {json.dumps(ru, ensure_ascii=False)}: {json.dumps(tr[idx], ensure_ascii=False)}," for ru, tr in seen.items()]
        body = HEADER + f"window.CHECKAI_LOCALES.{lang} = {{\n" + "\n".join(lines) + "\n};\n"
        with open(os.path.join(out_dir, f"{lang}.js"), "w", encoding="utf-8", newline="\n") as f:
            f.write(body)
    print(f"ok: {len(seen)} ключей → locales/kk.js, locales/en.js")


if __name__ == "__main__":
    build()
